#!/usr/bin/env python3
"""results/summary.json -> paper/numbers.tex

Every quantity that appears in the paper is a macro defined here.  The paper text
therefore contains no hand-typed numbers: if a run changes, the paper changes with
it, and CLAIMS.md can point at exactly one file per claim.
"""

from __future__ import annotations

import json
import os
import sys
from scipy import stats

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)

RES = os.path.join(HERE, "results")
OUT = os.path.join(HERE, "numbers.tex")

NAME = {"invoices": "Invoices", "emails": "Emails",
        "cleansing": "Cleanse", "reports": "Reports"}
PRIMARY = "qwen2.5:14b-instruct"
SECOND = "llama3.1:8b"


def f(x, nd=2):
    if x is None:
        return "n/a"
    if isinstance(x, bool):
        return "yes" if x else "no"
    if abs(x) >= 100:
        return f"{x:.0f}"
    if abs(x) >= 10:
        return f"{x:.1f}"
    return f"{x:.{nd}f}"


def pct(x, nd=0):
    if x is None or x != x:          # None or NaN
        return "n/a"
    return f"{x:.{nd}f}\\%"


BASE_N = 150
GUARD_N = 40


def main():
    s = json.load(open(os.path.join(RES, "summary.json")))
    pooled = s["pooled"]
    lines = ["% generated by emit_numbers.py - do not edit by hand",
             f"% source: results/summary.json  ({s['n_records']} records)", ""]

    def mac(name, val):
        lines.append(f"\\newcommand{{\\VD{name}}}{{{val}}}")

    mac("numRecords", s["n_records"])
    npc = s.get("n_per_cell", {})
    mac("nBase", npc.get("baseline", BASE_N))
    mac("nGuard", npc.get("guardrail", GUARD_N))
    mac("nFamilies", len(pooled))
    mac("rhoIn", f(s["calibration"]["rho_in"], 2))
    mac("rhoOut", f(s["calibration"]["rho_out"], 2))

    Ss = [r["S"] / r["n"] for r in pooled]      # per-product, not the family sum
    mac("smin", f"{min(Ss):.0f}")
    mac("smax", f"{max(Ss):.0f}")
    mac("sratio", f"{max(Ss)/min(Ss):.2f}")

    rk = s["pooled_rank"]
    mac("spearman", f(rk["spearman"], 2))
    mac("pperm", f(rk["p_perm"], 2))

    bars = s["bars"]
    mac("barB", "met" if bars.get("B1_any_family_D_ge_1") else "missed")
    mac("barC", "met" if bars.get("B2_monotone") else "missed")
    mac("barD", "met" if bars.get("B3_met") else "missed")
    mac("worstFamily", NAME.get(bars.get("B1_worst_family"), "n/a"))

    # worst-family aliases so the prose never hardcodes which family is worst
    worst = bars.get("B1_worst_family")
    if worst:
        wrow = next((r for r in pooled if r["family"] == worst), None)
        if wrow:
            mac("WorstD", f(wrow["D"]))
            mac("WorstDlo", f(wrow["D_lo"]))
            mac("WorstDhi", f(wrow["D_hi"]))
        gw = next((r for r in s["pooled_guardrail"] if r["family"] == worst), None)
        if gw:
            mac("WorstGuardCut", pct(gw["cut_pct"]))
            mac("WorstGuardCost", pct(gw["throughput_cost_pct"]))
            mac("WorstGuardD", f(gw["D_guard"]))
            mac("WorstGuardBase", f(gw["D_base"]))
            mac("WorstGuardDlo", f(gw.get("delta_lo")))
            mac("WorstGuardDhi", f(gw.get("delta_hi")))

    for r in pooled:
        F = NAME[r["family"]]
        mac(f"{F}S", f"{r['S']/1000:.1f}")
        mac(f"{F}V", f"{r['V']/1000:.1f}")
        mac(f"{F}R", f"{r['R']/1000:.1f}")
        mac(f"{F}D", f(r["D"]))
        mac(f"{F}Dlo", f(r["D_lo"]))
        mac(f"{F}Dhi", f(r["D_hi"]))
        mac(f"{F}Dmean", f(r["D_mean"]))
        mac(f"{F}VS", f(r["V_over_S"]))
        mac(f"{F}RS", f(r["R_over_S"]))
        mac(f"{F}Vis", f(s["verifiability"][r["family"]], 3))
        mac(f"{F}Pass", pct(100 * r["pass1_accept"]))
        mac(f"{F}Final", pct(100 * r["final_accept"]))
        mac(f"{F}VerAcc", pct(100 * r["verifier_accept"]))
        mac(f"{F}RwRate", pct(100 * r["rework_rate"]))
        mac(f"{F}Rounds", f(r["mean_rounds"]))
        mac(f"{F}Effort", f"{r['effort_per_product']:.0f}")
        mac(f"{F}Dfull", f(r["D_full"]))
        mac(f"{F}N", r["n"])

    Dvals = [r["D"] for r in pooled]
    mac("Dmin", f(min(Dvals)))
    mac("Dmax", f(max(Dvals)))
    Dfulls = [r["D_full"] for r in pooled]
    mac("dfullMin", f(min(Dfulls)))
    mac("dfullMax", f(max(Dfulls)))
    fp_n = sum(r["n"] for r in pooled)
    fp_acc = sum(r["pass1_accept"] * r["n"] for r in pooled)
    mac("firstPass", f"{fp_acc:.0f}")
    mac("firstPassRate", pct(100 * fp_acc / fp_n))

    for r in s["pooled_guardrail"]:
        F = NAME[r["family"]]
        mac(f"{F}GuardBase", f(r["D_base"]))        # matched baseline
        mac(f"{F}GuardD", f(r["D_guard"]))
        mac(f"{F}GuardDelta", pct(r["cut_pct"]))    # signed: + = debt decreased (a real cut)
        mac(f"{F}GuardChange", pct(-r["cut_pct"]))   # % change in D, + = debt rose
        mac(f"{F}GuardCost", pct(r["throughput_cost_pct"]))
        mac(f"{F}GuardPass", pct(100 * r["pass1_accept_guard"]))
        mac(f"{F}GuardDlo", f(r.get("delta_lo")))
        mac(f"{F}GuardDhi", f(r.get("delta_hi")))
    if s["pooled_guardrail"]:
        cuts = [r["cut_pct"] for r in s["pooled_guardrail"]]
        costs = [r["throughput_cost_pct"] for r in s["pooled_guardrail"]]
        mac("guardDeltaLo", pct(min(cuts)))
        mac("guardDeltaHi", pct(max(cuts)))
        # debt rose everywhere here (cut_pct < 0), so report the rise as a positive magnitude
        mac("guardRiseLo", pct(-max(cuts)))
        mac("guardRiseHi", pct(-min(cuts)))
        mac("guardCostLo", pct(min(costs)))
        mac("guardCostHi", pct(max(costs)))

    for model, tab in s["by_model"].items():
        if model.endswith("__rank"):
            continue
        pre = "q" if model == PRIMARY else "l"
        for r in tab:
            mac(f"{pre}D{NAME[r['family']]}", f(r["D"]))
        rank = s["by_model"].get(model + "__rank", {})
        mac(f"{pre}Spearman", f(rank.get("spearman"), 2))
        mac(f"{pre}Pperm", f(rank.get("p_perm"), 2))

    for model, lk in s["leakage"].items():
        pre = "q" if model == PRIMARY else "l"
        mac(f"{pre}Leak", pct(100 * lk["leak_rate"], 1))
        mac(f"{pre}LeakCrit", pct(100 * lk["leak_critical"], 1))
        mac(f"{pre}LeakN", lk["n_accepted"])

    # sensitivity band: min and max D over lambda for the worst family
    sens = [r for r in s.get("sensitivity", []) if r["model"] == PRIMARY]
    if sens:
        worst = bars.get("B1_worst_family")
        ws = [r["D"] for r in sens if r["family"] == worst]
        if ws:
            mac("sensMin", f(min(ws)))
            mac("sensMax", f(max(ws)))

    # loop-termination sensitivity: D under alternative cap / stall patience, for the
    # worst family on the primary model (a measurement choice, replayed offline)
    tsens = s.get("termination_sensitivity", [])
    if tsens:
        worst = bars.get("B1_worst_family")

        def _td(cap, pat):
            # pooled over models, ratio-of-sums: the deployed rule reproduces the
            # reported pooled D exactly, so this is comparable to Table 2.
            vs = [r["D"] for r in tsens if r["model"] == "pooled"
                  and r["family"] == worst and r["cap"] == cap and r["patience"] == pat]
            return vs[0] if vs else None
        # NB: macro names must not end in a digit --- TeX control words are
        # letters only, so a trailing digit terminates the name and breaks \newcommand.
        mac("termCapA", f(_td(1, 2)))
        mac("termCapB", f(_td(2, 2)))
        mac("termCapC", f(_td(3, 2)))
        mac("termCapE", f(_td(5, 2)))
        mac("termPatA", f(_td(5, 1)))

    # verifier-vs-census product-level agreement at first pass (quantified
    # false-rejection component of the debt; see measure/debt.detection_agreement)
    da = s.get("detection_agreement") or {}
    p = da.get("pooled") or {}
    if p:
        mac("detTP", str(p.get("TP", 0)))
        mac("detFP", str(p.get("FP", 0)))
        mac("detFN", str(p.get("FN", 0)))
        mac("detTN", str(p.get("TN", 0)))
        mac("detPrec", pct(100 * p["precision"]) if p.get("precision") is not None else "n/a")
        mac("detRec", pct(100 * p["recall"]) if p.get("recall") is not None else "n/a")
        mac("detFalseRej", pct(100 * p["false_rej_share"]) if p.get("false_rej_share") is not None else "n/a")
        mac("detReworkFalse", pct(100 * p["rework_false_share"]) if p.get("rework_false_share") is not None else "n/a")
        for fam_key, d in (da.get("by_family") or {}).items():
            F = NAME[fam_key]
            mac(f"det{F}Prec", pct(100 * d["precision"]) if d.get("precision") is not None else "n/a")
            mac(f"det{F}FalseRej", pct(100 * d["false_rej_share"]) if d.get("false_rej_share") is not None else "n/a")
            mac(f"det{F}ReworkFalse", pct(100 * d["rework_false_share"]) if d.get("rework_false_share") is not None else "n/a")

    # baseline total (denominator for first-pass counts; excludes the guardrail arm)
    if pooled:
        mac("nBaseline", str(sum(r["n"] for r in pooled)))
    # pooled baseline verifier accept across BOTH models, to match the pooled gold
    # count (1/40) in the Fisher comparison --- avoids a caliber mismatch
    bm = s.get("by_model", {})
    ba = sum(r.get("verifier_accept", 0) * r.get("n", 0)
             for m, tab in bm.items() if not m.endswith("__rank") for r in tab)
    bn = sum(r.get("n", 0) for m, tab in bm.items() if not m.endswith("__rank") for r in tab)
    if bn:
        mac("BaseAccPooled", f"{int(round(ba))}/{int(bn)}")

    # checker-attributable V+R (whole trajectories whose first rejection was false)
    ca = s.get("checker_attribution") or {}
    if ca and ca.get("share") is not None:
        mac("chkShare", pct(100 * ca["share"]))
        mac("chkShareLo", pct(100 * ca["share_lo"]))
        mac("chkShareHi", pct(100 * ca["share_hi"]))
        mac("chkD", f(ca["D_check"]))
        mac("chkDLo", f(ca["D_check_lo"]))
        mac("chkDHi", f(ca["D_check_hi"]))
        if ca.get("D_total") is not None:
            mac("chkDTotal", f(ca["D_total"]))

    # per-family check counts (used in the verifiability discussion)
    checks = s.get("n_checks", {})
    for fam_key, v in checks.items():
        mac(f"checks{NAME[fam_key]}", v)

    # break-even conversion factor lambda* = 1/D, per family (POOLED over models)
    lam = [(row["family"], 1.0 / row["D"]) for row in pooled if row["D"] > 0]
    if lam:
        mac("lambdaStarMin", f(min(x[1] for x in lam), 2))
        mac("lambdaStarMax", f(max(x[1] for x in lam), 2))
    # primary-model lambda* (the caliber Figure 4 / the sensitivity band uses)
    lamq = [1.0 / r["D"] for r in s["by_model"].get(PRIMARY, []) if r.get("D", 0) > 0]
    if lamq:
        mac("lambdaStarQMin", f(min(lamq), 3))
        mac("lambdaStarQMax", f(max(lamq), 3))

    # how much of the checker's effort is re-reading rather than emitting
    ts = s.get("token_split", {})
    if ts:
        shares = list(ts.values())
        mac("promptShareMin", pct(100 * min(shares)))
        mac("promptShareMax", pct(100 * max(shares)))
    vr = s.get("verifier_recall", {})
    if vr and vr.get("recall") is not None:
        mac("verRecall", pct(100 * vr["recall"], 1))
        mac("verCaught", vr["n_caught"])
        mac("verBlocked", vr["n_blocked"])

    # positive control (gold through verifier + census), if present
    gfiles = [os.path.join(RES, fn) for fn in os.listdir(RES)
              if fn.startswith("gold_control__") and fn.endswith(".json")]
    golds = [json.load(open(p)) for p in sorted(gfiles)]
    if golds:
        Dg = [r["D_gold"] for g in golds for r in g["families"].values()]
        fr = [r["false_reject_rate"] for g in golds for r in g["families"].values()]
        mac("goldDmin", f(min(Dg)))
        mac("goldDmax", f(max(Dg)))
        mac("goldFrMin", pct(100 * min(fr)))
        mac("goldFrMax", pct(100 * max(fr)))
        # pooled reject rate across BOTH models, with a Clopper-Pearson 95% CI
        acc = sum(r["verifier_accept_gold"] for g in golds for r in g["families"].values())
        nn = sum(r["n"] for g in golds for r in g["families"].values())
        rej = nn - acc
        # Clopper-Pearson exact 95% CI (portable across scipy versions)
        lo = 0.0 if rej == 0 else stats.beta.ppf(0.025, rej, nn - rej + 1)
        hi = 1.0 if rej == nn else stats.beta.ppf(0.975, rej + 1, nn - rej)
        mac("goldRej", f"{rej}/{nn}")
        mac("goldAcc", f"{acc}/{nn}")
        mac("goldRejPct", pct(100 * rej / nn))
        mac("goldRejRate", pct(100 * rej / nn, nd=1))   # 97.5\%, not rounded to 98\%
        mac("goldRejLo", pct(100 * lo))
        mac("goldRejHi", pct(100 * hi))
        # per family, BOTH models (table)
        for g in golds:
            M = "qwen" if g["model"] == PRIMARY else "llama"
            for fam, row in g["families"].items():
                F = NAME[fam]
                mac(f"GoldD{M}{F}", f(row["D_gold"]))
                mac(f"GoldFr{M}{F}", pct(100 * row["false_reject_rate"]))
                mac(f"GoldAcc{M}{F}", f"{row['verifier_accept_gold']}/{row['n']}")
        # primary-only aliases (inline prose that cites one model)
        gp = next((g for g in golds if g["model"] == PRIMARY), None)
        if gp:
            for fam, row in gp["families"].items():
                F = NAME[fam]
                mac(f"GoldD{F}", f(row["D_gold"]))
                mac(f"GoldFr{F}", pct(100 * row["false_reject_rate"]))
                mac(f"GoldAcc{F}", f"{row['verifier_accept_gold']}/{row['n']}")

    # pooled baseline (production) verifier acceptance per model, and the gold-vs-baseline
    # discrimination test (Fisher exact, primary model) used in the positive-control discussion
    for model, tab in s["by_model"].items():
        if model.endswith("__rank"):
            continue
        pre = "q" if model == PRIMARY else "l"
        acc = sum(r.get("verifier_accept", 0) * r.get("n", 0) for r in tab)
        nn = sum(r.get("n", 0) for r in tab)
        mac(f"{pre}BaseAcc", f"{int(round(acc))}/{int(nn)}")
    if golds:
        # pooled over BOTH models on both sides (gold 1/40 vs baseline 2/280), so the
        # Fisher table matches the displayed counts and does not mix calibers
        g_acc = sum(r["verifier_accept_gold"] for g in golds for r in g["families"].values())
        g_n = sum(r["n"] for g in golds for r in g["families"].values())
        b_acc = sum(r.get("verifier_accept", 0) * r.get("n", 0)
                    for m, tab in s["by_model"].items() if not m.endswith("__rank") for r in tab)
        b_n = sum(r.get("n", 0)
                  for m, tab in s["by_model"].items() if not m.endswith("__rank") for r in tab)
        a_g, a_b = int(round(g_acc)), int(round(b_acc))
        _, p = stats.fisher_exact([[a_g, g_n - a_g], [a_b, b_n - a_b]])
        mac("goldFisher", f"{p:.2f}")

    with open(OUT, "w") as fh:
        fh.write("\n".join(lines) + "\n")
    print(f"wrote {OUT} ({len(lines)} macros)")


if __name__ == "__main__":
    main()
